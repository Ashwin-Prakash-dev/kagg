"""
Assemble results/EXPERIMENT_REPORT.md from what is available on Kaggle.

    python scripts/build_experiment_report.py
    python scripts/build_experiment_report.py --results-root /kaggle/working/results

Sections 1-4 (research design, dataset, model, controls) are fully determined
by configs/master.yaml and the bundled data/ship_only/stats.json + docs/, and
are written every time. Sections 5+ (measured results) are written only once
results/master_results.csv exists; until then they are explicit "not yet run"
placeholders. Nothing is ever estimated, interpolated, or filled in from
expectation.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd
import yaml

PKG = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PKG))

from src.paths import annotation_dir, find_results_root

PENDING = ("_Not yet run. This section is generated from "
           "`results/master_results.csv`, which does not exist yet._")


def fmt(v, nd=4) -> str:
    if v is None or (isinstance(v, float) and pd.isna(v)):
        return "—"
    return f"{v:.{nd}f}" if isinstance(v, float) else f"{v:,}"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results-root", default=None)
    args = ap.parse_args()

    results_root = find_results_root(args.results_root)
    cfg = yaml.safe_load((PKG / "configs" / "master.yaml").read_text())
    ann = annotation_dir()
    stats_path = ann / "stats.json"
    stats = json.loads(stats_path.read_text()) if stats_path.exists() else None

    results_csv = results_root / "master_results.csv"
    have_results = results_csv.exists()
    res = pd.read_csv(results_csv) if have_results else None
    if res is not None and "sanity" in res:
        res = res[~res["sanity"]]

    L: list[str] = []
    A = L.append

    A("# Resolution and ship detection in FAIR1M -- experiment report")
    A("")
    A("Generated by `scripts/build_experiment_report.py` on Kaggle. Every "
      "figure traces to `configs/master.yaml`, `data/ship_only/stats.json`, "
      "`docs/`, or a file under `results/`.")
    A("")
    if not have_results:
        A("> **Status: dataset preparation complete, GPU sweep not yet run "
          "(or still in progress) on this Kaggle session.** Sections 1-4 are "
          "final. Sections 5+ are placeholders until "
          "`results/master_results.csv` exists.")
        A("")

    # ---------------------------------------------------------------- 1
    A("## 1. Research question")
    A("")
    A("> " + cfg["study"]["question"].strip())
    A("")
    A("The independent variable is the spatial resolution of the imagery. "
      "Four conditions are compared:")
    A("")
    A("| Condition | Label | Linear scale | Pixel area retained |")
    A("|---|---|---:|---:|")
    for k, e in cfg["experiments"].items():
        A(f"| {k} | {e['label']} | {e['scale']:.2f} | {e['scale'] ** 2 * 100:.2f}% |")
    A("")
    A("Downsampling scales area by the **square** of the linear factor. "
      "Halving the resolution removes three quarters of an object's pixel "
      "footprint -- the reason a size-stratified analysis is necessary, not "
      "optional.")
    A("")
    A("Dependent variables: " + ", ".join(cfg["evaluation"]["metrics"]) + ". "
      "Secondary: training time, inference latency, GPU memory, detection "
      "count.")
    A("")

    # ---------------------------------------------------------------- 2
    A("## 2. Dataset")
    A("")
    ds = cfg["dataset"]
    A(f"FAIR1M v1.0, {ds['split']['train_ships'] + ds['split']['val_ships']:,} "
      f"ship instances over {ds['split']['train_images'] + ds['split']['val_images']:,} "
      f"ship-containing images, single class (`ship`) collapsed from "
      f"{len(ds['ship_categories'])} FAIR1M categories.")
    A("")
    A("| | Train | Val | Total |")
    A("|---|---:|---:|---:|")
    A(f"| Images | {ds['split']['train_images']:,} | {ds['split']['val_images']:,} | "
      f"{ds['split']['train_images'] + ds['split']['val_images']:,} |")
    A(f"| Ship instances | {ds['split']['train_ships']:,} | {ds['split']['val_ships']:,} | "
      f"{ds['split']['train_ships'] + ds['split']['val_ships']:,} |")
    A("")
    if stats:
        A(f"Background policy: {ds['background_images']['retained']:,} ship-free "
          f"images retained from {ds['background_images']['available']:,} "
          f"available (fraction {ds['background_images']['fraction']}, seed "
          f"{ds['background_images']['seed']}).")
        A("")

    A("### Ship geometry (median across all instances, at original resolution)")
    A("")
    A("| Metric | Approx. value |")
    A("|---|---:|")
    A("| width | ~38 px |")
    A("| height | ~36 px |")
    A("| area | ~1,376 px² |")
    A("")
    A("Full distribution and the reasoning behind the object-size bins: "
      "`docs/object_size_definition.md`.")
    A("")

    A("### What downsampling does to small ships")
    A("")
    A("Share of ships whose **longest side** falls below 8 px, by condition "
      "(originally-small ships hold together to r50 and then collapse):")
    A("")
    A("| Resolution | % below 8 px (longest side) |")
    A("|---|---:|")
    for label, pct in [("original", 0.0), ("75%", 0.6), ("50%", 6.6), ("25%", 68.5)]:
        A(f"| {label} | {pct:.1f}% |")
    A("")
    A("This is the study's central, pre-registered hypothesis: if measured "
      "AP follows this pattern, the mechanism is loss of pixel support; if it "
      "does not, the model is relying on context rather than object detail.")
    A("")

    # ---------------------------------------------------------------- 3
    A("## 3. Dataset cleaning")
    A("")
    A("297 degenerate annotations (FAIR1M tiling artefacts -- objects whose "
      "polygon collapses onto a tile boundary) were removed; 109 genuinely "
      "tiny-but-valid objects were retained. **None of the 297 removals is a "
      "ship** -- all 58,982 ship annotations are geometrically valid. Full "
      "audit trail: `docs/cleaning_report.md`.")
    A("")

    # ---------------------------------------------------------------- 4
    A("## 4. Experimental design and controls")
    A("")
    A("Held identical across all four conditions: train/val split, image "
      "identities, annotation identities, architecture, optimizer, "
      "learning-rate schedule, augmentation policy, epochs, batch size, "
      "evaluation procedure, confidence/NMS thresholds, and random seed. "
      "`src/training.py` mechanically enforces this: an experiment may only "
      "override `{data, name, project, seed}` and raises on anything else.")
    A("")
    t = cfg["train"]
    A("| Parameter | Value |")
    A("|---|---|")
    A(f"| model | {cfg['model']['arch']} ({cfg['model']['weights']}) |")
    for k in ("epochs", "batch", "imgsz", "optimizer", "lr0", "lrf"):
        A(f"| `{k}` | {t[k]} |")
    A(f"| `seed` | {cfg['reproducibility']['seed']} |")
    ev = cfg["evaluation"]
    A(f"| eval `conf` / `iou` / `max_det` | {ev['conf']} / {ev['iou']} / "
      f"{ev['max_det']} |")
    A("")
    A(f"**`imgsz={t['imgsz']}`, identical in every condition.** This is the "
      f"key control: at the Ultralytics default of 640 the dataloader would "
      f"itself downsample E00 and E01 to nearly the same effective detail, "
      f"collapsing the contrast between conditions before training started.")
    A("")
    A(f"**`max_det={ev['max_det']}`, raised from the default 300.** The "
      f"densest validation tile holds 581 ships; 300 would silently cap "
      f"recall on exactly the crowded harbour scenes this study is about.")
    A("")
    ob = cfg["object_size_bins"]
    A(f"**Object-size bins** (`small < {ob['small_max_px2']:,} px²`, "
      f"`medium {ob['small_max_px2']:,}-{ob['medium_max_px2']:,} px²`, "
      f"`large ≥ {ob['medium_max_px2']:,} px²`) are COCO absolute-area "
      f"thresholds measured on the **original-resolution** box, assigned "
      f"once and never recomputed per resolution.")
    A("")

    # ------------------------------------------------------------- 5+
    def results_section(num: int, title: str, body_if_ready) -> None:
        A(f"## {num}. {title}")
        A("")
        if have_results and res is not None and len(res):
            body_if_ready()
        else:
            A(PENDING)
        A("")

    def baseline_body():
        b = res[res["resolution"] == "original"]
        if b.empty:
            A("_Baseline condition has not been run._")
            return
        b = b.iloc[0]
        A("| Metric | Value |")
        A("|---|---:|")
        for k, lbl in [("mAP50", "mAP@50"), ("mAP50_95", "mAP@50:95"),
                       ("precision", "precision"), ("recall", "recall"),
                       ("f1", "F1"), ("AP_small", "AP small"),
                       ("AP_medium", "AP medium"), ("AP_large", "AP large")]:
            A(f"| {lbl} | {fmt(b.get(k))} |")
        A("")

    def resolution_body():
        cols = ["resolution", "mAP50", "mAP50_95", "precision", "recall", "f1"]
        A("| " + " | ".join(cols) + " |")
        A("|" + "---|" * len(cols))
        for _, r in res.iterrows():
            A("| " + " | ".join(fmt(r.get(c)) if c != "resolution" else str(r[c])
                                for c in cols) + " |")
        A("")
        drop = [c for c in res.columns if c.endswith("_drop_pct")]
        if drop:
            A("Degradation relative to baseline (%, positive = worse):")
            A("")
            A("| resolution | " + " | ".join(d.replace("_drop_pct", "") for d in drop) + " |")
            A("|" + "---|" * (len(drop) + 1))
            for _, r in res.iterrows():
                A(f"| {r['resolution']} | " +
                  " | ".join(fmt(r.get(d), 2) for d in drop) + " |")
            A("")

    def size_body():
        A("| Resolution | Overall mAP@50:95 | AP small | AP medium | AP large |")
        A("|---|---:|---:|---:|---:|")
        for _, r in res.iterrows():
            A(f"| {r['resolution']} | {fmt(r.get('mAP50_95'))} | "
              f"{fmt(r.get('AP_small'))} | {fmt(r.get('AP_medium'))} | "
              f"{fmt(r.get('AP_large'))} |")
        A("")
        A("Ground-truth support per bin (small / medium / large): "
          f"{fmt(res.iloc[0].get('n_gt_small'))} / "
          f"{fmt(res.iloc[0].get('n_gt_medium'))} / "
          f"{fmt(res.iloc[0].get('n_gt_large'))}.")
        A("")

    def cost_body():
        A("| Resolution | Training (h) | Latency (ms/img) | Peak GPU (GB) | GPU |")
        A("|---|---:|---:|---:|---|")
        for _, r in res.iterrows():
            A(f"| {r['resolution']} | {fmt(r.get('training_time_h'), 2)} | "
              f"{fmt(r.get('latency_ms_per_image'), 1)} | "
              f"{fmt(r.get('peak_gpu_memory_gb'), 2)} | {r.get('gpu', '—')} |")
        A("")
        A("Network input size is held constant, so these costs are expected "
          "to be similar across conditions. A study that scaled `imgsz` with "
          "resolution would show large savings here, at the price of "
          "confounding resolution with compute.")
        A("")

    results_section(5, "Baseline results (E00, original resolution)", baseline_body)
    results_section(6, "Resolution results", resolution_body)
    results_section(7, "Object-size results", size_body)

    A("## 8. Qualitative results")
    A("")
    scene_index = results_root / "qualitative" / "scene_index.json"
    if scene_index.exists():
        n = len(json.loads(scene_index.read_text())["scenes"])
        A(f"{n} matched scenes rendered across conditions -- see "
          f"`results/qualitative/`.")
    else:
        A("_Requires trained models. `scripts/qualitative_comparison.py` "
          "renders the same scenes at all four resolutions with predictions "
          "overlaid, into `results/qualitative/`._")
    A("")

    results_section(9, "Computational cost", cost_body)

    # ---------------------------------------------------------------- 10
    A("## 10. Limitations")
    A("")
    A("- **Simulated, not native, low resolution.** Downsampling models a "
      "coarser sensor's spatial sampling; it does not reproduce sensor "
      "noise, optical MTF or atmospheric effects, so results are an "
      "optimistic bound relative to genuinely lower-resolution imagery.")
    A(f"- **Single seed** (seed {cfg['reproducibility']['seed']}) unless the "
      f"optional repeated-seed runs are executed. One run per condition "
      f"supports no claim of statistical significance.")
    A("- **Split not balanced for ships.** The official FAIR1M Val split is "
      "denser in ships than Train. Constant across conditions, so the "
      "comparison holds, but absolute numbers are not directly comparable "
      "to a different split.")
    A("- **Single architecture.** Findings are for YOLOv8m only.")
    A("- **Axis-aligned boxes.** FAIR1M ships are annotated as oriented "
      "boxes; this study uses their axis-aligned extent.")
    A("")

    # ---------------------------------------------------------------- 11
    A("## 11. Conclusions")
    A("")
    if have_results and res is not None and len(res):
        A("_Draft from the measured numbers above. Keep observation, "
          "interpretation and hypothesis separate; make no causal claim "
          "beyond what the design supports._")
    else:
        A("_Awaiting results from the Kaggle GPU sweep._")
    A("")

    results_root.mkdir(parents=True, exist_ok=True)
    out = results_root / "EXPERIMENT_REPORT.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print(f"Wrote {out}")
    print(f"  results present: {have_results}"
          f"{'' if have_results else '  (sections 5-9 are placeholders)'}")


if __name__ == "__main__":
    main()
